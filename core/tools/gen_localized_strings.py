#!/usr/bin/env python3
"""Generate the overlay string table from RPCS3's Qt string collection.

RPCS3's native overlays (Big Picture Mode, home menu, dialogs) ask the frontend for their
text through g_emu_callbacks.get_localized_string. On desktop that is answered by
rpcs3qt/localized_emu.h, a switch of Qt tr() calls. This script extracts the English source
strings from that switch so the Xbox frontend can answer without Qt, then applies the
Xbox-specific replacements from overrides.txt.

Usage: gen_localized_strings.py <localized_emu.h> <overrides.txt> <output.inc>
"""
import re
import sys

CASE_RE = re.compile(
    r'case\s+localized_string_id::(\w+)\s*:\s*return\s+(?:tr\(\s*)?((?:"(?:[^"\\]|\\.)*"\s*)+)',
    re.S)
LITERAL_RE = re.compile(r'"((?:[^"\\]|\\.)*)"')


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)

    source_path, overrides_path, output_path = sys.argv[1:]

    with open(source_path, encoding='utf-8') as f:
        source = f.read()

    # Only the translated() switch, not translated_pad_button() and friends
    strings = {}
    for name, literals in CASE_RE.findall(source):
        if name not in strings:
            strings[name] = ''.join(LITERAL_RE.findall(literals))

    overrides = 0
    with open(overrides_path, encoding='utf-8') as f:
        for line in f:
            line = line.rstrip('\n')
            if not line.strip() or line.lstrip().startswith('#'):
                continue
            name, _, text = line.partition('=')
            strings[name.strip()] = text.strip()
            overrides += 1

    if len(strings) < 100:
        sys.exit(f'Only {len(strings)} strings found in {source_path}; the file format changed')

    with open(output_path, 'w', encoding='utf-8', newline='\n') as out:
        out.write('// Generated by core/tools/gen_localized_strings.py. Do not edit.\n')
        for name in sorted(strings):
            out.write(f'{{ localized_string_id::{name}, u8"{strings[name]}" }},\n')

    print(f'{len(strings)} strings ({overrides} Xbox overrides) -> {output_path}')


if __name__ == '__main__':
    main()
